ALTER TABLE admin.user_report ADD COLUMN evidence TEXT;

CREATE TABLE admin.account_deletion_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES identity.users (id),
    requested_by  BIGINT       NOT NULL REFERENCES identity.users (id),
    reason        VARCHAR(500) NOT NULL,
    status        VARCHAR(10)  NOT NULL DEFAULT 'pending'
        CONSTRAINT chk_account_deletion_status CHECK (status IN ('pending', 'approved', 'rejected')),
    decided_by    BIGINT REFERENCES identity.users (id),
    decision_note VARCHAR(500),
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    decided_at    TIMESTAMP
);
CREATE INDEX idx_account_deletion_status ON admin.account_deletion_request (status);
