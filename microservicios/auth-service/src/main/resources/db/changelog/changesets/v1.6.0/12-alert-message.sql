-- Chat de la alerta: mensajes entre quien activó la alerta (owner) y sus contactos (contact), con
-- mensajes rápidos predeterminados o texto libre. Sin trigger de auditoría a propósito: el
-- contenido de los mensajes es sensible y no debe copiarse en admin.audit_log.

--changeset alerta-mujer-team:v1.6.0-alert-message
CREATE TABLE alert.alert_message (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id     BIGINT       NOT NULL REFERENCES alert.alert (id) ON DELETE CASCADE,
    sender_type  VARCHAR(10)  NOT NULL CHECK (sender_type IN ('owner', 'contact')),
    sender_name  VARCHAR(60)  NOT NULL,
    body         VARCHAR(500) NOT NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_alert_message_alert ON alert.alert_message (alert_id, id);
--rollback DROP TABLE IF EXISTS alert.alert_message;
