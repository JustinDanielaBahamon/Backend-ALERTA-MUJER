-- "Avísame si no llego": la usuaria avisa a dónde va y en cuánto llega. Si no confirma su llegada a
-- tiempo, el servidor activa una alerta con su última ubicación conocida (aunque el celular esté
-- sin datos ni saldo en ese momento).

--changeset alerta-mujer-team:v1.6.0-safe-trip
CREATE TABLE alert.safe_trip (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_profile_id       BIGINT       NOT NULL REFERENCES identity.user_profile (id),
    user_id               BIGINT       NOT NULL,
    device_id             BIGINT       NOT NULL,
    destination           VARCHAR(120) NOT NULL,
    destination_latitude  NUMERIC(9, 6),
    destination_longitude NUMERIC(9, 6),
    started_at            TIMESTAMP    NOT NULL,
    expected_arrival      TIMESTAMP    NOT NULL,
    status                VARCHAR(12)  NOT NULL DEFAULT 'active'
        CONSTRAINT chk_safe_trip_status CHECK (status IN ('active', 'arrived', 'cancelled', 'alerted')),
    reminder_sent         BOOLEAN      NOT NULL DEFAULT false,
    alert_id              BIGINT REFERENCES alert.alert (id),
    ended_at              TIMESTAMP,
    created_at            TIMESTAMP    NOT NULL DEFAULT now()
);
-- Solo un trayecto activo por usuaria, y el revisor busca rápido los que están por vencer
CREATE UNIQUE INDEX uq_safe_trip_one_active ON alert.safe_trip (user_profile_id) WHERE status = 'active';
CREATE INDEX idx_safe_trip_active_arrival ON alert.safe_trip (expected_arrival) WHERE status = 'active';
--rollback DROP TABLE alert.safe_trip;
