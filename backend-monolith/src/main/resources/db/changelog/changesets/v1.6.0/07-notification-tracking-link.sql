-- Esquema del módulo de notificaciones (futuro servicio de notificaciones).
-- tracking_link: enlaces públicos de seguimiento que se envían por correo a los contactos de
-- una alerta. Se guarda solo el hash SHA-256 del código; el código completo solo viaja en el correo.
-- alert_id no tiene llave foránea a propósito: el esquema no depende de otro módulo (ver
-- docs/arquitectura/monolito-modular.md); la alerta se valida por la API del módulo alerts.

--changeset alerta-mujer-team:v1.6.0-notification-schema splitStatements:false
CREATE SCHEMA IF NOT EXISTS notification;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'alerta_app') THEN
        GRANT USAGE ON SCHEMA notification TO alerta_app;
        ALTER DEFAULT PRIVILEGES IN SCHEMA notification GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO alerta_app;
        ALTER DEFAULT PRIVILEGES IN SCHEMA notification GRANT USAGE, SELECT ON SEQUENCES TO alerta_app;
    END IF;
END $$;
--rollback DROP SCHEMA IF EXISTS notification CASCADE;

--changeset alerta-mujer-team:v1.6.0-notification-tracking-link
CREATE TABLE notification.tracking_link (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id    BIGINT      NOT NULL,
    token_hash  CHAR(64)    NOT NULL UNIQUE,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at  TIMESTAMP
);
CREATE INDEX idx_tracking_link_alert ON notification.tracking_link (alert_id);
--rollback DROP TABLE IF EXISTS notification.tracking_link;
